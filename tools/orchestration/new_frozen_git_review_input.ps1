[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$Workspace,

    [Parameter(Mandatory = $true)]
    [string]$OutputPath
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Resolve-Directory([string]$Path, [string]$Label) {
    if (-not (Test-Path -LiteralPath $Path -PathType Container)) { throw "$Label does not exist: $Path" }
    return [System.IO.Path]::GetFullPath((Resolve-Path -LiteralPath $Path).Path)
}

function Invoke-GitText([string[]]$GitArgs) {
    $output = @(& git -C $workspacePath @GitArgs 2>&1)
    if ($LASTEXITCODE -ne 0) { throw "git $($GitArgs -join ' ') failed: $($output -join [Environment]::NewLine)" }
    return @($output | ForEach-Object { [string]$_ })
}

$workspacePath = Resolve-Directory $Workspace 'Workspace'
$inside = @(& git -C $workspacePath rev-parse --is-inside-work-tree 2>&1)
if ($LASTEXITCODE -ne 0 -or ($inside -join '').Trim() -ne 'true') { throw 'Workspace must be a Git worktree' }

$output = [System.IO.Path]::GetFullPath($OutputPath)
if (-not [System.IO.Path]::IsPathRooted($output)) { throw 'OutputPath must be absolute' }
$parent = Split-Path -Parent $output
if (Test-Path -LiteralPath $output) { throw "OutputPath already exists: $output" }
if (Test-Path -LiteralPath $parent) {
    if (@(Get-ChildItem -LiteralPath $parent -Force).Count -ne 0) { throw 'OutputPath parent must be a dedicated empty directory' }
}
else {
    New-Item -ItemType Directory -Path $parent | Out-Null
}

$head = (Invoke-GitText @('rev-parse', 'HEAD') | Select-Object -First 1).Trim()
$status = Invoke-GitText @('status', '--porcelain=v1', '-b', '--untracked-files=all')
$unstaged = Invoke-GitText @('diff', '--no-ext-diff', '--no-color', '--no-textconv', '--unified=3')
$staged = Invoke-GitText @('diff', '--cached', '--no-ext-diff', '--no-color', '--no-textconv', '--unified=3')
$untrackedPaths = Invoke-GitText @('ls-files', '--others', '--exclude-standard')

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Frozen Git review input')
$lines.Add('')
$lines.Add('This artifact was generated by the host from read-only Git commands. It is immutable after routing; the managed framework verifies its SHA-256 before launch.')
$lines.Add('')
$lines.Add('## Repository identity')
$lines.Add('')
$lines.Add("HEAD: ``$head``")
$lines.Add('')
$lines.Add('## Git status')
$lines.Add('')
$lines.Add('```text')
foreach ($line in $status) { $lines.Add($line) }
$lines.Add('```')
$lines.Add('')
$lines.Add('## Unstaged diff')
$lines.Add('')
$lines.Add('```diff')
foreach ($line in $unstaged) { $lines.Add($line) }
$lines.Add('```')
$lines.Add('')
$lines.Add('## Staged diff')
$lines.Add('')
$lines.Add('```diff')
foreach ($line in $staged) { $lines.Add($line) }
$lines.Add('```')
$lines.Add('')
$lines.Add('## Untracked files')
$lines.Add('')
$lines.Add('| Path | Bytes | SHA-256 |')
$lines.Add('| --- | ---: | --- |')
foreach ($relative in $untrackedPaths) {
    $full = [System.IO.Path]::GetFullPath((Join-Path $workspacePath $relative))
    $prefix = $workspacePath.TrimEnd('\', '/') + [System.IO.Path]::DirectorySeparatorChar
    if (-not $full.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)) { throw "untracked path escaped Workspace: $relative" }
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { continue }
    $item = Get-Item -LiteralPath $full
    $hash = (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash.ToLowerInvariant()
    $escaped = $relative.Replace('|', '\|')
    $lines.Add("| $escaped | $($item.Length) | ``$hash`` |")
}
$lines.Add('')
$lines.Add('## Reviewer boundary')
$lines.Add('')
$lines.Add('- Treat the Git status and diffs above as the frozen repository delta for this review.')
$lines.Add('- Use read-only file tools to inspect referenced workspace files when more context is required.')
$lines.Add('- Do not run Shell, modify files, stage, commit, or treat technical release as business approval.')

$content = ($lines -join "`n") + "`n"
[System.IO.File]::WriteAllText($output, $content, [System.Text.UTF8Encoding]::new($false))
$hash = (Get-FileHash -LiteralPath $output -Algorithm SHA256).Hash.ToLowerInvariant()
$item = Get-Item -LiteralPath $output
[pscustomobject]@{
    schema_version = 1
    name = 'repository-review'
    path = $item.FullName
    root = $item.Directory.FullName
    format = 'markdown'
    bytes = $item.Length
    sha256 = $hash
    git_head = $head
} | ConvertTo-Json -Depth 4
